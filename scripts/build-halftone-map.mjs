// scripts/build-halftone-map.mjs — สร้างแผนที่จุด halftone ไทย + ประเทศเพื่อนบ้าน
//   → public/maps/thailand-halftone.svg (ปก/ภาพแชร์ — นิ่ง) + thailand-halftone-pulse.svg (จอ QR — มีคลื่นกรุงเทพฯ)
// ใช้ข้อมูล Natural Earth (world-atlas 50m) · รันครั้งเดียว (ไฟล์ผลลัพธ์ commit ไว้ ไม่ต้องรันตอน build)
//   node scripts/build-halftone-map.mjs
// ไทย = จุดใหญ่ ทึบกว่า · เพื่อนบ้าน = จุดเล็ก จาง และเล็กลงตามระยะห่างจากไทย (ให้ไทยเด่น)
// สีจุด = ส้มอ่อน (orange-200) ไม่ใช่ขาว — ขาวสว่างเกินจนแย่งสายตาและทำให้ตัวหนังสือบนปกอ่านยาก
import fs from 'fs';
import { createRequire } from 'module';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const world = require('world-atlas/countries-50m.json');
const countries = feature(world, world.objects.countries).features;

// กรอบแผนที่ (ลองจิจูด/ละติจูด) — ไทยอยู่กลาง เห็นเมียนมา ลาว กัมพูชา เวียดนาม มาเลเซีย บางส่วนของจีน/อินเดีย
const LON0 = 87.5, LON1 = 114.5, LAT0 = -1.5, LAT1 = 28.5;
const W = 1000;
const K = Math.cos((13 * Math.PI) / 180); // ปรับสัดส่วนแนวนอนที่ละติจูดไทย
const H = Math.round((W * (LAT1 - LAT0)) / ((LON1 - LON0) * K));
const toLon = (x) => LON0 + (x / W) * (LON1 - LON0);
const toLat = (y) => LAT1 - (y / H) * (LAT1 - LAT0);

const SPACING = 9; // ระยะจุด (หน่วย viewBox)
const TH_CENTER = [100.9, 13.5]; // จุดกลางโดยประมาณของไทย (ใช้คำนวณการจางของเพื่อนบ้าน)

// point-in-polygon (ray casting) รองรับ Polygon / MultiPolygon พร้อมรู
function inRing(lon, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
function inGeometry(lon, lat, g) {
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [];
  return polys.some(([outer, ...holes]) => inRing(lon, lat, outer) && !holes.some((h) => inRing(lon, lat, h)));
}
function bbox(g) {
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  let a = [Infinity, Infinity, -Infinity, -Infinity];
  for (const p of polys) for (const [x, y] of p[0]) a = [Math.min(a[0], x), Math.min(a[1], y), Math.max(a[2], x), Math.max(a[3], y)];
  return a;
}

const inFrame = countries
  .filter((f) => f.geometry)
  .map((f) => ({ name: f.properties.name, geometry: f.geometry, box: bbox(f.geometry) }))
  .filter(({ box }) => box[2] >= LON0 && box[0] <= LON1 && box[3] >= LAT0 && box[1] <= LAT1);

const dot = (x, y, r) => `M${(x - r).toFixed(1)} ${y.toFixed(1)}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`;
let th = '', near = '';
let nTh = 0, nNear = 0;
for (let row = 0, y = SPACING / 2; y < H; row++, y += SPACING * 0.866) {
  // แถวเยื้องกัน (ตารางหกเหลี่ยม) แบบ halftone สิ่งพิมพ์
  for (let x = (row % 2 ? SPACING / 2 : 0) + SPACING / 2; x < W; x += SPACING) {
    const lon = toLon(x), lat = toLat(y);
    const hit = inFrame.find((c) => lon >= c.box[0] && lon <= c.box[2] && lat >= c.box[1] && lat <= c.box[3] && inGeometry(lon, lat, c.geometry));
    if (!hit) continue;
    if (hit.name === 'Thailand') {
      th += dot(x, y, 3.3);
      nTh++;
    } else {
      // เล็กลงตามระยะจากไทย: ใกล้ 2.2 → ไกล 0.9
      const d = Math.hypot((lon - TH_CENTER[0]) * K, lat - TH_CENTER[1]);
      const r = Math.max(0.9, 2.2 - d * 0.09);
      near += dot(x, y, +r.toFixed(2));
      nNear++;
    }
  }
}

// กรุงเทพฯ (ที่ตั้งรัฐสภา) — จุด + คลื่นวงแหวน 3 วงกระจายออก (CSS animation ใน SVG — ทำงานแม้ใช้เป็น <img>)
const BKK = [100.5018, 13.7563];
const bx = (((BKK[0] - LON0) / (LON1 - LON0)) * W).toFixed(1);
const by = (((LAT1 - BKK[1]) / (LAT1 - LAT0)) * H).toFixed(1);
const pulse = `<style>
.r{fill:none;stroke:#fff7ed;stroke-width:1.1;transform-box:fill-box;transform-origin:center;opacity:0;animation:p 4.2s cubic-bezier(.2,.6,.3,1) infinite}
.r2{animation-delay:1.4s}.r3{animation-delay:2.8s}
@keyframes p{0%{transform:scale(.4);opacity:.55}100%{transform:scale(9);opacity:0}}
@media (prefers-reduced-motion:reduce){.r{animation:none;opacity:0}}
</style>
<circle class="r" cx="${bx}" cy="${by}" r="6"/><circle class="r r2" cx="${bx}" cy="${by}" r="6"/><circle class="r r3" cx="${bx}" cy="${by}" r="6"/>
<circle cx="${bx}" cy="${by}" r="4.2" fill="#fff7ed"/>`;

// 2 ไฟล์: ปกใช้แบบนิ่ง (ไม่มีจุด/คลื่นกรุงเทพฯ — ไม่แย่งความสนใจจากข้อความ) · จอ QR ในห้องประชุมใช้แบบมีคลื่น
const build = (withPulse) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" preserveAspectRatio="xMidYMid slice" aria-hidden="true">
<!-- Halftone map: Thailand + neighbours. Data: Natural Earth (public domain) via world-atlas. Generated by scripts/build-halftone-map.mjs -->
<path fill="#fed7aa" fill-opacity="0.22" d="${near}"/>
<path fill="#fed7aa" fill-opacity="0.42" d="${th}"/>
${withPulse ? pulse : ''}
</svg>
`;
for (const [file, withPulse] of [['public/maps/thailand-halftone.svg', false], ['public/maps/thailand-halftone-pulse.svg', true]]) {
  const svg = build(withPulse);
  fs.writeFileSync(file, svg);
  console.log(`✓ ${file} ${W}×${H} · Thailand ${nTh} dots · neighbours ${nNear} dots · ${(svg.length / 1024).toFixed(0)} KB`);
}
